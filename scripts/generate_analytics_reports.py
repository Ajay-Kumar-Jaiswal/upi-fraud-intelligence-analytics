#!/usr/bin/env python3
"""
Generates reports/analytics_validation.md and reports/join_coverage_report.csv
by running every analytics function defined in src/analytics/ against the
cleaned, validated data and recording actual results (nothing here is
pre-written - this script executes the real functions each time it runs).
"""
import sys
import json
from pathlib import Path
from datetime import datetime, timezone, timedelta

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import pandas as pd
from src.config import REPORTS_DIR
from src.analytics.transactions_kpi import transaction_kpis, utr_quality_kpis
from src.analytics.chargebacks_kpi import (
    chargeback_txn_join_coverage, chargeback_core_kpis, chargebacks_by,
    chargebacks_by_merchant, top_users_by_disputed_amount, dispute_reporting_delay_kpis,
)
from src.analytics.merchant_category import (
    merchant_category_join_coverage, merchant_category_performance,
    bonus_question_highest_chargeback_ratio_category,
)
from src.analytics.merchant_analytics import (
    merchant_master_join_coverage, merchant_master_enriched_ranking, top_merchants_by_chargeback_ratio,
)
from src.analytics.kyc_analytics import (
    kyc_population_kpis, kyc_join_coverage, transaction_behavior_by_kyc_status, suspicious_identity_indicators,
)
from src.analytics.time_analytics import data_date_range_summary, monthly_transaction_trend
from src.analytics.advanced_insights import (
    utr_missing_vs_status, chargeback_concentration, negative_amount_status_correlation, repeated_chargeback_users,
)

IST = timezone(timedelta(hours=5, minutes=30))


def main():
    REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    generated_at = datetime.now(IST).strftime("%Y-%m-%d %H:%M:%S IST")

    txn_k = transaction_kpis()
    utr_k = utr_quality_kpis()
    cb_join = chargeback_txn_join_coverage()
    cb_k = chargeback_core_kpis()
    cb_by_reason = chargebacks_by("reason_code")
    cb_by_severity = chargebacks_by("severity")
    cb_by_status = chargebacks_by("resolution_status")
    cb_by_channel = chargebacks_by("channel")
    cat_cov = merchant_category_join_coverage()
    cat_perf = merchant_category_performance()
    bonus = bonus_question_highest_chargeback_ratio_category()
    mm_cov = merchant_master_join_coverage()
    top_merchants = top_merchants_by_chargeback_ratio(min_transactions=5, top_n=10)
    kyc_pop = kyc_population_kpis()
    kyc_cov = kyc_join_coverage()
    kyc_behavior = transaction_behavior_by_kyc_status()
    synthetic = suspicious_identity_indicators()
    date_range = data_date_range_summary()
    monthly = monthly_transaction_trend()
    utr_vs_status = utr_missing_vs_status()
    concentration = chargeback_concentration()
    neg_corr = negative_amount_status_correlation()
    repeat_users = repeated_chargeback_users()

    # ---- consolidated join coverage CSV -----------------------------------
    coverage_rows = [
        cat_cov["step_1_any_merchant_match"],
        cat_cov["step_2_unambiguous_category_match"],
        mm_cov,
        kyc_cov["step_1_any_user_match"],
        kyc_cov["step_2_unambiguous_kyc_status_match"],
        cb_join,
    ]
    pd.DataFrame(coverage_rows).to_csv(REPORTS_DIR / "join_coverage_report.csv", index=False)

